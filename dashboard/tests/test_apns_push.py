import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
_tmp = tempfile.mkdtemp(prefix="apns-push-test-")
os.environ["CHIEF_DASHBOARD_CONFIG_HOME"] = _tmp
os.environ["AGENTBAR_APNS_DEVICES_FILE"] = os.path.join(_tmp, "apns-devices.json")
