import apns_push  # noqa: E402

# Off in production (user choice); the send path is still tested with it on.
check_off = permission_push.PERMISSION_PUSH_ENABLED
permission_push.PERMISSION_PUSH_ENABLED = True
import hook_permission_routes as routes  # noqa: E402

fails = []
TOKEN_A, TOKEN_B = "a" * 64, "b" * 64


def check(label, got, want):
    ok = got == want
    if not ok:
        fails.append(f"{label}: got {got!r} want {want!r}")
    print(f"  {'PASS' if ok else 'FAIL'}  {label}")


def b64url_decode(text):
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


KEY_PATH = os.path.join(_tmp, "AuthKey_TEST.p8")
subprocess.run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", KEY_PATH], check=True)
CONFIG = {"keyPath": KEY_PATH, "keyId": "KEYID", "teamId": "TEAMID", "bundleId": "app.test", "sandbox": True}


class FakeTransport:
    def __init__(self, replies=None):
        self.calls, self.replies = [], replies or {}

    def __call__(self, url, headers, body):
        self.calls.append((url, headers, json.loads(body)))
        return self.replies.get(url.rsplit("/", 1)[-1], (200, None))


def pusher_with(transport, registry, configured=True):
    client = apns_push.ApnsClient(CONFIG, post=transport) if configured else None
    return permission_push.PermissionPusher(client_factory=lambda: client, registry=registry,
                                            run_async=lambda work: work())


PAYLOAD = {"session_id": "s1", "tool_name": "Bash", "cwd": "/Users/x/01_Project/AptusFit",
           "tool_input": {"command": "npm test -- --watch=false " + "x" * 100}}

print("config")
check("missing config -> off", apns_push.load_config(os.path.join(_tmp, "nope.json")), None)
cfg_path = os.path.join(_tmp, "apns.json")
with open(cfg_path, "w") as f:
    json.dump({**CONFIG, "keyId": ""}, f)
check("incomplete config -> off", apns_push.load_config(cfg_path), None)
with open(cfg_path, "w") as f:
    json.dump(CONFIG, f)
check("full config -> on", apns_push.load_config(cfg_path)["bundleId"], "app.test")

print("provider token (ES256)")
clock = [1000.0]
client = apns_push.ApnsClient(CONFIG, post=FakeTransport(), clock=lambda: clock[0])
jwt = client.provider_token()
header, claims, signature = jwt.split(".")
check("jwt header", json.loads(b64url_decode(header)), {"alg": "ES256", "kid": "KEYID"})
check("jwt claims", json.loads(b64url_decode(claims)), {"iss": "TEAMID", "iat": 1000})
check("jose signature is 64 bytes", len(b64url_decode(signature)), 64)
try:
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec, utils
    raw = b64url_decode(signature)
    with open(KEY_PATH, "rb") as f:
        public = serialization.load_pem_private_key(f.read(), None).public_key()
    der = utils.encode_dss_signature(int.from_bytes(raw[:32], "big"), int.from_bytes(raw[32:], "big"))
    public.verify(der, f"{header}.{claims}".encode(), ec.ECDSA(hashes.SHA256()))
    check("signature verifies", True, True)
except ImportError:
    print("  SKIP  signature verify (no cryptography module)")
clock[0] += 49 * 60
check("token cached < 50 min", client.provider_token(), jwt)
clock[0] += 2 * 60
check("token refreshed after 50 min", client.provider_token() != jwt, True)

print("unconfigured = no-op")
registry = apns_devices.DeviceRegistry(os.path.join(_tmp, "devices-off.json"))
registry.add(TOKEN_A)
transport = FakeTransport()
pusher_with(transport, registry, configured=False).notify_registered("hp1-x", PAYLOAD)
check("no send when not configured", transport.calls, [])

print("alert + dedupe")
registry = apns_devices.DeviceRegistry(os.path.join(_tmp, "devices.json"))
registry.add(TOKEN_A, "iPhone")
transport = FakeTransport()
pusher = pusher_with(transport, registry)
pusher.notify_registered("hp1-x", PAYLOAD)
pusher.notify_registered("hp1-x", PAYLOAD)
check("one push per requestId", len(transport.calls), 1)
url, headers, body = transport.calls[0]
check("sandbox host + device path", url, "https://api.sandbox.push.apple.com/3/device/" + TOKEN_A)
check("collapse id = requestId", headers["apns-collapse-id"], "hp1-x")
check("topic = bundle id", headers["apns-topic"], "app.test")
check("category", body["aps"]["category"], "AGENT_PERMISSION")
check("agent = folder name", body["agent"], "AptusFit")
check("summary <= SUMMARY_MAX_CHARS", len(body["summary"]) <= permission_push.SUMMARY_MAX_CHARS, True)
check("summary text", body["summary"].startswith("Run a shell command: npm test"), True)
pusher.notify_answered("hp1-x")
check("answered -> silent withdraw push", (transport.calls[-1][1]["apns-push-type"], transport.calls[-1][2]["withdrawn"]),
      ("background", "hp1-x"))
pusher.notify_answered("hp-never-pushed")
check("never-pushed answer -> nothing", len(transport.calls), 2)

print("dead tokens dropped")
registry.add(TOKEN_B)
transport = FakeTransport({TOKEN_A: (410, "Unregistered"), TOKEN_B: (400, "BadDeviceToken")})
pusher_with(transport, registry).notify_registered("hp2-y", PAYLOAD)
check("both tried", len(transport.calls), 2)
check("410 + BadDeviceToken removed", registry.tokens(), [])
registry.add(TOKEN_A)
transport = FakeTransport({TOKEN_A: (429, "TooManyRequests")})
pusher_with(transport, registry).notify_registered("hp3-z", PAYLOAD)
check("transient error keeps token", registry.tokens(), [TOKEN_A])

print("device routes + 0600 file")
devices_reg = apns_devices.DeviceRegistry(os.path.join(_tmp, "routes.json"))
reply = apns_devices.handle("POST", "/api/apns/devices", lambda: {"deviceToken": TOKEN_A.upper(), "label": " Watch "}, devices_reg)
check("register ok", reply, ({"ok": True}, 200))
check("file mode 0600", stat.S_IMODE(os.stat(devices_reg.path).st_mode), 0o600)
check("token stored lowercase", devices_reg.tokens(), [TOKEN_A])
check("bad token -> 400", apns_devices.handle("POST", "/api/apns/devices", lambda: {"deviceToken": "$(echo INJECTED)"}, devices_reg)[1], 400)
check("unregister", apns_devices.handle("DELETE", "/api/apns/devices", lambda: {"deviceToken": TOKEN_A}, devices_reg), ({"ok": True, "removed": True}, 200))
check("other path -> None", apns_devices.handle("POST", "/api/other", lambda: {}, devices_reg), None)

print("hook route trigger")


class FakeStore:
    def register(self, payload, entry=None):
        return {"requestId": "hp9-r"}

    def answer(self, request_id, body):
        return {"ok": True, "state": "answered"}, 200


class RecordingPusher:
    def __init__(self):
        self.events = []

    def notify_registered(self, request_id, payload):
        self.events.append(("registered", request_id))

    def notify_answered(self, request_id):
        self.events.append(("answered", request_id))


recorder = RecordingPusher()
routes.handle_post("/api/hook/permission", lambda: PAYLOAD, False, store=FakeStore(),
                   session_entry=lambda p: None, pusher=recorder)
routes.handle_post("/api/hook/permission/hp9-r/answer", lambda: {"behavior": "allow"}, True,
                   store=FakeStore(), pusher=recorder)
check("register + answer reach the pusher", recorder.events, [("registered", "hp9-r"), ("answered", "hp9-r")])

print("permission push off by default")
check("PERMISSION_PUSH_ENABLED default", check_off, False)
permission_push.PERMISSION_PUSH_ENABLED = False
off_sent = []
off = permission_push.PermissionPusher(
    client_factory=lambda: None, registry=None, run_async=lambda fn: fn())
off._fan_out.send = lambda *a, **k: off_sent.append(a)
off.notify_registered("hp-off", {"tool_name": "Bash", "tool_input": {"command": "ls"}})
check("disabled -> nothing sent", off_sent, [])

